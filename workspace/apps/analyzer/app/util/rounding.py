"""四舍五入 —— **全项目唯一**的取整口径（part3 spec §2.3 / AC28）。

## 为什么必须只有一处

AC28 要求「手算复现」：评审当场拿维度分与权重口算一遍，结果要等于接口返回值。
口算用的必然是**四舍五入**，而 Python 内置 `round` 是**银行家舍入**（`round(12.5) == 12`、
`round(0.5) == 0`）—— 两者在 `.5` 上不一致，且不一致得非常隐蔽：
只有恰好落在 `.5` 的输入才会暴露，平时怎么测都是对的。

part2 的 `matcher.score_of` 已经踩过这个坑并写了注释。part3 的 `ability_profile.overall`
是**第二个**分数公式，如果它自己写一遍 `round`，早晚会漂移成两种口径 ——
所以把口径抽到这里，两个公式**共用同一个函数**（结构上保证一致，而不是靠注释约定）。
"""

from __future__ import annotations
import math


def round_half_up(value: float) -> int:
    """四舍五入（`.5` 一律进位）。

    `math.floor(value + 0.5)` 而不是 `round(value)`：
    - 与口算口径一致（AC28）；
    - 对负数同样成立（`floor(-1.5 + 0.5) == -1`），虽然本项目的分数恒为 0–100 的非负数，
      但一个「只在正数上正确」的工具函数迟早会在别处被误用。

    不用 `Decimal`：分数只有两位有效数字，浮点误差远小于 0.5 的判据阈值
    （`sum(权重)` 的误差在 1e-16 量级，与 1e-9 的容差差着七个数量级）。
    """
    return int(math.floor(value + 0.5))
